// Базовый матфильтр: слово целиком заменяется звёздочками.
// Ловит латинские двойники букв (xуй, cука), разделители (х.у.й) и повторы (хууууй).
const LAT={a:'а',b:'в',c:'с',e:'е',h:'н',k:'к',m:'м',o:'о',p:'р',t:'т',x:'х',y:'у',u:'и',3:'з',0:'о',6:'б','@':'а','ё':'е'};
const BAD=[
  /(хуй|хуе|хуи|хуя|хую|хул[иь]|хуев|хуит)/,
  /пизд|пезд/,
  /^(за|вы|въ|от|до|на|по|у|раз|рас|об|объ|под|про|съ|долбо|ъ)?еб(а|у|л|н|и|о|ш|ет|ыр|ук|ен)/,
  /^(за|вы|от|до|на|по|у|раз|рас|об|под|про|съ)?ебл/,
  /^бля/, /^бляд/,
  /^(сук[аиуе]$|сукин|сучк|сучар|сучь)/,
  /^муда[кч]|^мудил|^мудо[зе]/,
  /^п[ие]д[оа]р|^пидр|^педик/,
  /^г[ао]нд[оа]н/, /^залуп/, /^шлюх/, /^шалав/, /^дроч/, /^манд[ауеыо]$|^мандав/,
  /^долбо[её]б|^уеб|^уебк|^ебл[оа]/,
];
function norm(w){
  let s='';for(const ch of w.toLowerCase())s+=LAT[ch]||ch;
  s=s.replace(/[^а-я]/g,'');           // убираем точки, звёздочки, дефисы между буквами
  return s.replace(/(.)\1+/g,'$1');      // хууууй → хуй
}
export function isBad(w){const n=norm(w).replace(/страху|оскорбля/g,'');return n.length>1&&BAD.some(r=>r.test(n));}
export function clean(text){
  return String(text??'').split(/(\s+)/).map(w=>/\s/.test(w)||!isBad(w)?w:'*'.repeat(Math.min(w.length,6))).join('');
}
